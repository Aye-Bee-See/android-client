#!/usr/bin/env node
// Emits crypto material using the API's own services/crypto.js so the Kotlin
// tests can prove they interoperate with the server-side primitives.
//
//   node tools/make-interop-fixture.mjs /path/to/sqlite-express-api
//
// Writes crypto/src/test/resources/interop/node-fixture.properties.
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const apiDir = process.argv[2];
if (!apiDir) {
  console.error('usage: make-interop-fixture.mjs <path to sqlite-express-api>');
  process.exit(2);
}
process.chdir(apiDir); // services/crypto.js reads .env through #constants
const crypto = await import(pathToFileURL(resolve(apiDir, 'services/crypto.js')).href);
await crypto.ready;

const plaintext = 'Dear Bill, the tomatoes are in. — encrypted by node';
const contentKey = crypto.generateContentKey();
const body = crypto.encrypt(plaintext, contentKey);
const kp = crypto.keypair();
const sealedContentKey = crypto.sealTo(kp.publicKey, contentKey);

const lines = [
  '# Generated by tools/make-interop-fixture.mjs; do not edit.',
  `plaintext=${plaintext}`,
  `contentKey=${crypto.encode(contentKey)}`,
  `ciphertext=${body.ciphertext}`,
  `nonce=${body.nonce}`,
  `publicKey=${kp.publicKey}`,
  `privateKey=${kp.privateKey}`,
  `sealedContentKey=${sealedContentKey}`,
];
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../crypto/src/test/resources/interop/node-fixture.properties');
writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote', out);
